#!/usr/bin/env python3
"""Fill in the launcher templates from house.json.

usage: render_home.py <house.json> <out_dir> [--print-env]

Writes
  <out_dir>/assets/home.html            home.html with __FEATURES__ / __WALLPAPER__ / __SLIDES__ / __LANG__ / __SERVER__ filled in
  <out_dir>/assets/modules/*            optional feature modules (cards, quips, plex, warp), copied as they are
  <out_dir>/gen/dev/skippy/channel/Config.java   constants the Java side needs

With --print-env it prints shell assignments (VIDEO_FIRE / VIDEO_TV) for wallpaper.mode == "video".
Used by channel-app/build.sh and by the headless preview, so both see the same page.
"""
import json, os, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FEATURES = ('cards', 'quips', 'plex', 'bridge', 'watchnext', 'warp')


def die(msg):
    sys.exit('render_home: ' + msg)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    if len(args) != 2:
        die(__doc__)
    house_path, out = args
    with open(house_path, encoding='utf-8') as f:
        h = json.load(f)

    feats = {k: bool(h.get('features', {}).get(k, False)) for k in FEATURES}
    wall = {'mode': h.get('wallpaper', {}).get('mode', 'slideshow')}
    if wall['mode'] not in ('slideshow', 'video'):
        die('wallpaper.mode must be "slideshow" or "video"')
    server = (h.get('server', {}).get('public_url') or '').rstrip('/')
    cam = h.get('camera', {})
    cam_ts = f"{cam['go2rtc'].rstrip('/')}/api/stream.ts?src={cam['stream']}&video=h264" if cam.get('go2rtc') and cam.get('stream') else ''

    # a feature that needs the cards server is useless without it: fail loudly instead of showing an empty row
    for k in ('cards', 'quips', 'plex', 'watchnext', 'bridge'):
        if feats[k] and not server:
            die(f'features.{k} needs server.public_url in house.json (see house.skippy.json)')
    if feats['bridge'] and not cam_ts:
        die('features.bridge needs camera.go2rtc and camera.stream in house.json')

    slides_path = os.path.join(ROOT, 'wallpapers', 'slides.json')
    slides = None
    if os.path.exists(slides_path):
        with open(slides_path, encoding='utf-8') as f:
            slides = json.load(f)

    with open(os.path.join(ROOT, 'channel-app', 'assets', 'home.html'), encoding='utf-8') as f:
        html = f.read()
    subs = {
        '__FEATURES__': json.dumps(feats),
        '__WALLPAPER__': json.dumps(wall),
        '__SLIDES__': json.dumps(slides),
        '__LANG__': h.get('language', 'en-GB'),
        '__SERVER__': server,
    }
    for k, v in subs.items():
        html = html.replace(k, v)

    os.makedirs(os.path.join(out, 'assets'), exist_ok=True)
    with open(os.path.join(out, 'assets', 'home.html'), 'w', encoding='utf-8') as f:
        f.write(html)
    mods = os.path.join(out, 'assets', 'modules')
    shutil.rmtree(mods, ignore_errors=True)
    shutil.copytree(os.path.join(ROOT, 'channel-app', 'assets', 'modules'), mods)

    cfg_dir = os.path.join(out, 'gen', 'dev', 'skippy', 'channel')
    os.makedirs(cfg_dir, exist_ok=True)
    with open(os.path.join(cfg_dir, 'Config.java'), 'w', encoding='utf-8') as f:
        f.write('package dev.skippy.channel;\n'
                '// GENERATED by tools/render_home.py from house.json: do not edit\n'
                'final class Config {\n'
                f'    static final String SERVER = "{server}";\n'
                f'    static final String CAM_TS = "{cam_ts}";\n'
                f'    static final boolean VIDEO = {str(wall["mode"] == "video").lower()};\n'
                f'    static final boolean WATCHNEXT = {str(feats["watchnext"]).lower()};\n'
                '}\n')

    if '--print-env' in sys.argv and wall['mode'] == 'video':
        devs = h.get('devices', [])
        fire = next((d for d in devs if d.get('fire_tv')), None)
        tv = next((d for d in devs if not d.get('fire_tv')), fire)
        if not (fire or tv):
            die('wallpaper.mode "video" needs devices[].wallpaper in house.json')
        print(f"VIDEO_FIRE='{(fire or tv)['wallpaper']}'")
        print(f"VIDEO_TV='{(tv or fire)['wallpaper']}'")


if __name__ == '__main__':
    main()
